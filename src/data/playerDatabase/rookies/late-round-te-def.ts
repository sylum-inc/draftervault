const createRookie = (
  id: string,
  name: string,
  pos: string,
  fantPos: string,
  team: string,
  college: string,
  height: string,
  weight: number,
  fortyYard?: number,
  vertical?: number,
  benchPress?: number,
  broadJump?: number,
  threeCone?: number,
  shuttle?: number,
  round: number = 7,
  pick: number = 200,
  overall: number = 65,
  athleticScore: number = 70
): RookieProfile => ({
  playerId: id,
  name,
  position: pos,
  fantasyPosition: fantPos,
  team,
  college,
  height,
  weight,
  age: 22,
  draft: { year: 2025, round, pick, overall: (round - 1) * 32 + pick },
  combine: {
    fortyYard,
    vertical,
    benchPress,
    broadJump,
    threeCone,
    shuttle,
    speedScore: fortyYard ? Math.round((weight * 200) / Math.pow(fortyYard, 4)) : undefined,
    athleticScore,
    source: 'COMBINE',
  },
  grades: { overall, athletic: athleticScore, production: overall - 5, situation: overall - 10 },
  projection: round <= 5 ? 'DEVELOPMENTAL' : 'DEPTH',
  dynasty: {
    oneYearValue: 40 - round * 4,
    threeYearValue: 50 - round * 4,
    fiveYearValue: 55 - round * 4,
  },
  sources: ['NFL_COMBINE', 'PFF', 'ESPN'],
});

